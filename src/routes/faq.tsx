const ALL = GROUPS.flatMap((g) => g.items);

export const Route = createFileRoute("/faq")({
  head: () => ({
    ...seo({
      title: "Често задавани въпроси",
      description:
        "Отговори за публикуване на задачи, кредити, отключване на контакти, плащания, отзиви и сигурност в ТърсяБГ. Кратко и на разбираем език.",
      path: "/faq",
    }),
    scripts: [
      jsonLd({
        "@context": "https://schema.org",
        "@type": "FAQPage",
        mainEntity: ALL.map((f) => ({
          "@type": "Question",
          name: f.q,
          acceptedAnswer: { "@type": "Answer", text: f.a },
        })),
      }),
      breadcrumbLd([
        { name: "Начало", path: "/" },
        { name: "Често задавани въпроси", path: "/faq" },
      ]),
    ],
  }),
  component: FaqPage,
});

function normalize(s: string) {
  return s.toLocaleLowerCase("bg-BG");
}

function FaqPage() {
  const [query, setQuery] = useState("");

  const groups = useMemo(() => {
    const q = normalize(query.trim());
    if (!q) return GROUPS;
    return GROUPS.map((g) => ({
      title: g.title,
      items: g.items.filter((i) => normalize(i.q).includes(q) || normalize(i.a).includes(q)),
    })).filter((g) => g.items.length > 0);
  }, [query]);

  const found = groups.reduce((n, g) => n + g.items.length, 0);

  return (
    <div className="container mx-auto max-w-3xl px-4 py-10 md:py-14">
      <header className="mb-6 text-center">
        <span className="inline-flex items-center gap-2 rounded-full bg-muted px-3 py-1 text-xs font-medium text-muted-foreground">
          <HelpCircle className="h-3.5 w-3.5" />
          Помощен център
        </span>
        <h1 className="mt-3 text-3xl font-bold tracking-tight md:text-4xl">Често задавани въпроси</h1>
        <p className="mt-2 text-muted-foreground">
          Кратки отговори за задачите, кредитите, плащанията и правилата на платформата.
        </p>
      </header>

      <div className="relative">
        <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-muted-foreground" />
        <Input
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          placeholder="Търси във въпросите..."
          aria-label="Търсене във въпросите"
          className="h-12 rounded-full pl-10"
        />
      </div>

      {query.trim() && (
        <p className="mt-3 text-sm text-muted-foreground">
          {found === 0
            ? "Няма съвпадения. Опитай с друга дума или ни пиши."
            : `${found} ${found === 1 ? "отговор" : "отговора"} по „${query.trim()}“`}
        </p>
      )}

      <div className="mt-8 space-y-8">
        {groups.map((group) => (
          <section key={group.title}>
            <h2 className="mb-3 text-lg font-semibold tracking-tight">{group.title}</h2>
            <Accordion type="single" collapsible className="rounded-2xl border border-border bg-card px-4">
              {group.items.map((item) => (
                <AccordionItem key={item.q} value={item.q} className="last:border-b-0">
                  <AccordionTrigger className="text-left text-base font-medium">{item.q}</AccordionTrigger>
                  <AccordionContent className="text-sm leading-relaxed text-muted-foreground">
                    {item.a}
                  </AccordionContent>
                </AccordionItem>
              ))}
            </Accordion>
          </section>
        ))}
      </div>

      <div className="mt-10 rounded-2xl border border-border bg-muted/40 p-6 text-center">
        <h2 className="text-lg font-semibold">Не намери отговор?</h2>
        <p className="mt-1 text-sm text-muted-foreground">
          Пиши ни и ще ти отговорим обикновено в рамките на един работен ден.
        </p>
        <Button asChild className="mt-4 rounded-full">
          <Link to="/contact">Свържи се с нас</Link>
        </Button>
      </div>
    </div>
  );
}
